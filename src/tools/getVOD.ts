import { z } from 'zod';
import { CallToolResult } from '@modelcontextprotocol/sdk/types.js';
import { MyWhooshClient } from '../clients/mywhoosh.js';
import { asMcpError, McpError } from './utils/toolHelpers.js';

export const method = 'getVOD';
export const description = `List the video-on-demand catalogue: recorded coached workouts as data[] with Id, Title, Description, Tags, CreatorId (matches a coach Id from getCoaches) and StreamUrl (an MPEG-DASH manifest). Read-only, it does not start anything.`;
export const parameters = z.object({});

export async function handler(
  args: z.infer<typeof parameters>,
  extra: { client: MyWhooshClient }
): Promise<CallToolResult> {
  try {
    const result = await extra.client.get('/client/vod', { baseUrl: 'COACHING' });
    return {
      content: [{ type: 'text', text: JSON.stringify(result, null, 2) }],
    };
  } catch (e) {
    if (e instanceof McpError) throw e;
    throw asMcpError(e);
  }
}
